GO

SELECT
    z.id_заказа,
    z.номер                         AS [Номер заказа],
    z.дата                          AS [Дата],
    pk.наименование                 AS [Покупатель],
    SUM(sz.количество * м.стоимость_материалов) AS [Полная стоимость]
FROM Заказ z
    JOIN Заказчик pk        ON pk.id_заказчика = z.id_покупателя
    JOIN Строка_заказа sz   ON sz.id_заказа = z.id_заказа
    JOIN (
            -- стоимость материалов на единицу каждой продукции
            SELECT s.id_продукции,
                   SUM(s.норма_расхода * m.цена) AS стоимость_материалов
            FROM Спецификация s
                JOIN Материал m ON m.id_материала = s.id_материала
            GROUP BY s.id_продукции
         ) AS м ON м.id_продукции = sz.id_продукции
GROUP BY z.id_заказа, z.номер, z.дата, pk.наименование
ORDER BY z.id_заказа;
GO
